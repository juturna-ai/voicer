def cell(s) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def render() -> str:
    lines = [
        "# Licenses", "",
        "Generated by `scripts/make_licenses.py` from `library/catalog.json`. Do not edit by hand.", "",
        "Only open-license models and voices are used. No voice imitates a real or famous person.",
        "\"Commercial\" = whether the license allows commercial use of the generated audio.",
        "Cloned voices use the model's license (XTTS-v2 and F5 are **non-commercial**). "
        "Only clone voices you own or have permission to use.", "",
        "## Models", "",
        "| Model | Used for | License | Commercial | Source |", "|---|---|---|---|---|",
    ]
    lines += [f"| {' | '.join(cell(x) for x in m)} |" for m in MODELS]
    voices = sorted(library.catalog(), key=lambda v: (v["language"], v["engine"], v["name"]))
    lines += ["", f"## Voices ({len(voices)})", "",
              "| Id | Name | Lang | Accent | Engine | License | Commercial | Source |",
              "|---|---|---|---|---|---|---|---|"]
    for v in voices:
        lic = f"[{cell(v['license'])}]({v['license_url']})" if v.get("license_url") else cell(v["license"])
        lines.append(f"| `{v['id']}` | {cell(v['name'])} | {v['language']} | {cell(v['accent'])} | {v['engine']} | "
                     f"{lic} | {'Yes' if v['commercial'] else 'No'} | {v['source_url']} |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUT.write_text(render())
    print("wrote", OUT)
